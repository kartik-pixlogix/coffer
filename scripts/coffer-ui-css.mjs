#!/usr/bin/env node
/*
 * Builds resources/css/coffer-ui.css from design/design-system/components/bundle.css (D22).
 *
 * Why: bundle.css starts with element resets scoped to `.cf` (`.cf button{font:inherit;
 * color:inherit}`, `.cf a{color:…}` …). Their specificity (0,1,1) beats single-class
 * component rules (0,1,0) such as `.cf-btn--primary{color:var(--on-graphite)}`, and in
 * the app the whole document is `.cf`, so buttons and links lose their component colour
 * and font. This script copies the bundle unchanged except for one mechanical edit:
 * every rule that is not one of those resets (or a `:where()` token block) gets
 * `:not(#\#)` on its subject, adding one id to its specificity. Component rules keep
 * their order relative to each other and the resets go back to being defaults.
 *
 * Usage: node scripts/coffer-ui-css.mjs   (writes the file; `npm run ui:css`)
 * A unit test (resources/js/lib/coffer-ui-css.test.ts) fails if the file drifts.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const BOOST = ':not(#\\#)';

/** Reset selectors that must stay weaker than every component rule. */
const RESETS = new Set([
    '.cf',
    '.cf *',
    '.cf *::before',
    '.cf *::after',
    '.cf a',
    '.cf a:hover',
    '.cf button',
    '.cf input',
    '.cf select',
    '.cf textarea',
    '.cf button:disabled',
    '.cf input::placeholder',
    '.cf textarea::placeholder',
]);

const HEADER =
    '/* GENERATED by scripts/coffer-ui-css.mjs from design/design-system/components/bundle.css.\n' +
    '   Do not edit: change the design bundle and run `npm run ui:css`. Component rules carry\n' +
    "   :not(#\\#) so the bundle's `.cf button` / `.cf a` resets cannot override them (D22). */\n";

/** Split a selector list on top-level commas (ignores commas inside parentheses). */
function splitSelectors(list) {
    const parts = [];
    let depth = 0;
    let current = '';

    for (const char of list) {
        if (char === '(') depth++;
        if (char === ')') depth--;

        if (char === ',' && depth === 0) {
            parts.push(current);
            current = '';
        } else {
            current += char;
        }
    }

    parts.push(current);

    return parts.map((part) => part.trim()).filter(Boolean);
}

/** Add the boost to the subject compound, before any pseudo-element. */
function boostSelector(selector) {
    const pseudoElement = selector.lastIndexOf('::');

    return pseudoElement === -1
        ? `${selector}${BOOST}`
        : `${selector.slice(0, pseudoElement)}${BOOST}${selector.slice(pseudoElement)}`;
}

function boostRuleSelector(list) {
    const selectors = splitSelectors(list);

    if (selectors.every((s) => RESETS.has(s) || s.startsWith(':where('))) {
        return list;
    }

    return selectors
        .map((s) =>
            RESETS.has(s) || s.startsWith(':where(') ? s : boostSelector(s),
        )
        .join(',');
}

/**
 * Walk the stylesheet, rewriting style-rule selectors. Comments, at-rule preludes,
 * @keyframes bodies and declarations are copied byte for byte.
 */
export function boostBundle(css) {
    let out = '';
    let i = 0;
    const stack = []; // 'rule' | 'block' (at-rule with nested rules) | 'keyframes'

    while (i < css.length) {
        const char = css[i];

        if (char === '/' && css[i + 1] === '*') {
            const end = css.indexOf('*/', i + 2);
            const stop = end === -1 ? css.length : end + 2;
            out += css.slice(i, stop);
            i = stop;
            continue;
        }

        if (char === '"' || char === "'") {
            let j = i + 1;
            while (j < css.length && css[j] !== char)
                j += css[j] === '\\' ? 2 : 1;
            out += css.slice(i, j + 1);
            i = j + 1;
            continue;
        }

        if (char === '}') {
            stack.pop();
            out += char;
            i++;
            continue;
        }

        const top = stack[stack.length - 1];

        if (top === 'rule' || top === 'keyframes') {
            if (char === '{') stack.push('rule');
            out += char;
            i++;
            continue;
        }

        // Prelude of a rule or at-rule: read up to the next '{' or ';'.
        let j = i;
        while (
            j < css.length &&
            css[j] !== '{' &&
            css[j] !== ';' &&
            css[j] !== '}'
        ) {
            if (css[j] === '/' && css[j + 1] === '*') break;

            if (css[j] === '"' || css[j] === "'") {
                const quote = css[j];
                j++;
                while (j < css.length && css[j] !== quote)
                    j += css[j] === '\\' ? 2 : 1;
            }

            j++;
        }

        if (css[j] === '/') {
            out += css.slice(i, j);
            i = j;
            continue;
        }

        const prelude = css.slice(i, j);
        const trimmed = prelude.trim();

        if (css[j] !== '{') {
            out += css.slice(i, j + (css[j] === ';' ? 1 : 0));
            i = j + (css[j] === ';' ? 1 : 0);
            continue;
        }

        if (trimmed === '') {
            out += prelude + '{';
            stack.push('rule');
        } else if (trimmed.startsWith('@')) {
            out += prelude + '{';
            stack.push(
                /^@(-webkit-)?keyframes/.test(trimmed) ? 'keyframes' : 'block',
            );
        } else {
            const leading = prelude.slice(0, prelude.indexOf(trimmed));
            const trailing = prelude.slice(
                prelude.indexOf(trimmed) + trimmed.length,
            );
            out += leading + boostRuleSelector(trimmed) + trailing + '{';
            stack.push('rule');
        }

        i = j + 1;
    }

    return HEADER + out;
}

export const paths = (() => {
    const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

    return {
        bundle: resolve(root, 'design/design-system/components/bundle.css'),
        output: resolve(root, 'resources/css/coffer-ui.css'),
    };
})();

if (
    process.argv[1] &&
    resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
    writeFileSync(
        paths.output,
        boostBundle(readFileSync(paths.bundle, 'utf8')),
    );
    console.log(`Wrote ${paths.output}`);
}
